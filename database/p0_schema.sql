CREATE TABLE IF NOT EXISTS payment_orders (
  id BIGINT NOT NULL COMMENT '支付单ID',
  payment_no VARCHAR(64) NOT NULL COMMENT '支付单号',
  order_id BIGINT NOT NULL COMMENT '订单ID',
  order_no VARCHAR(64) NOT NULL COMMENT '订单号',
  user_id BIGINT NOT NULL COMMENT '用户ID',
  channel VARCHAR(32) NOT NULL COMMENT '支付渠道',
  pay_amount DECIMAL(18,2) NOT NULL COMMENT '支付金额',
  pay_status VARCHAR(32) NOT NULL DEFAULT 'INIT' COMMENT 'INIT, PAYING, SUCCESS, FAILED, CLOSED',
  third_trade_no VARCHAR(128) NULL COMMENT '第三方交易号',
  idempotent_key VARCHAR(128) NULL COMMENT '幂等Key',
  paid_at DATETIME(3) NULL COMMENT '支付成功时间',
  callback_payload JSON NULL COMMENT '回调摘要',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_payment_no (payment_no),
  UNIQUE KEY uk_payment_order (order_id),
  UNIQUE KEY uk_payment_idempotent (idempotent_key),
  UNIQUE KEY uk_payment_third_trade (channel, third_trade_no),
  KEY idx_payment_status (pay_status),
  KEY idx_payment_channel_status (channel, pay_status),
  KEY idx_payment_user (user_id),
  CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES orders (id),
