-- 多商户电商平台 P0 版本数据库表结构
-- Target: MySQL 8.x / InnoDB / utf8mb4
-- 说明：
-- 1. 金额统一 DECIMAL(18,2)，状态统一 VARCHAR(32)。
-- 2. 所有核心业务表包含 deleted_at、created_at、updated_at、version。
-- 3. P0 使用数据库外键表达核心关系；若后续分库分表，可迁移为应用层逻辑外键。

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT NOT NULL COMMENT '用户ID',
  mobile VARCHAR(20) NOT NULL COMMENT '手机号',
  password_hash VARCHAR(255) NULL COMMENT '密码哈希',
  nickname VARCHAR(64) NULL COMMENT '昵称',
  avatar_url VARCHAR(500) NULL COMMENT '头像URL',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  last_login_at DATETIME(3) NULL COMMENT '最后登录时间',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_users_mobile (mobile),
  KEY idx_users_status (status),
  KEY idx_users_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户表';

CREATE TABLE IF NOT EXISTS user_addresses (
  id BIGINT NOT NULL COMMENT '地址ID',
  user_id BIGINT NOT NULL COMMENT '用户ID',
  receiver_name VARCHAR(64) NOT NULL COMMENT '收货人',
  receiver_mobile VARCHAR(20) NOT NULL COMMENT '收货手机号',
  province VARCHAR(64) NOT NULL COMMENT '省',
  city VARCHAR(64) NOT NULL COMMENT '市',
  district VARCHAR(64) NOT NULL COMMENT '区县',
  detail_address VARCHAR(255) NOT NULL COMMENT '详细地址',
  is_default TINYINT NOT NULL DEFAULT 0 COMMENT '是否默认地址',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  KEY idx_user_addresses_user (user_id),
  CONSTRAINT fk_user_addresses_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户收货地址表';

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT NOT NULL COMMENT '类目ID',
  parent_id BIGINT NULL COMMENT '父级类目ID',
  category_name VARCHAR(64) NOT NULL COMMENT '类目名称',
  level INT NOT NULL DEFAULT 1 COMMENT '层级',
  sort_no INT NOT NULL DEFAULT 0 COMMENT '排序',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  KEY idx_categories_parent (parent_id),
  KEY idx_categories_status (status),
  CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商品类目表';

CREATE TABLE IF NOT EXISTS merchants (
  id BIGINT NOT NULL COMMENT '商家ID',
  merchant_no VARCHAR(64) NOT NULL COMMENT '商家编号',
  owner_user_id BIGINT NOT NULL COMMENT '老板用户ID',
  company_name VARCHAR(128) NOT NULL COMMENT '主体名称',
  license_no VARCHAR(64) NOT NULL COMMENT '营业执照号',
  contact_name VARCHAR(64) NOT NULL COMMENT '联系人',
  contact_mobile VARCHAR(20) NOT NULL COMMENT '联系电话',
  audit_status VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, APPROVED, REJECTED',
  status VARCHAR(32) NOT NULL DEFAULT 'DISABLED' COMMENT 'ENABLED, FROZEN, DISABLED',
  reject_reason VARCHAR(500) NULL COMMENT '驳回原因',
  approved_at DATETIME(3) NULL COMMENT '审核通过时间',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_merchants_no (merchant_no),
  UNIQUE KEY uk_merchants_license_no (license_no),
  KEY idx_merchants_owner (owner_user_id),
  KEY idx_merchants_status (status, audit_status),
  CONSTRAINT fk_merchants_owner_user FOREIGN KEY (owner_user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商家主体表';

CREATE TABLE IF NOT EXISTS stores (
  id BIGINT NOT NULL COMMENT '店铺ID',
  merchant_id BIGINT NOT NULL COMMENT '商家ID',
  store_no VARCHAR(64) NOT NULL COMMENT '店铺编号',
  store_name VARCHAR(128) NOT NULL COMMENT '店铺名称',
