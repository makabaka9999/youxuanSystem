  CONSTRAINT fk_stores_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  CONSTRAINT fk_stores_category FOREIGN KEY (category_id) REFERENCES categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='店铺表';

CREATE TABLE IF NOT EXISTS merchant_staffs (
  id BIGINT NOT NULL COMMENT '商家员工ID',
  merchant_id BIGINT NOT NULL COMMENT '商家ID',
  user_id BIGINT NOT NULL COMMENT '用户ID',
  staff_name VARCHAR(64) NOT NULL COMMENT '员工姓名',
  role_type VARCHAR(32) NOT NULL COMMENT 'OWNER, STAFF',
  menu_permissions JSON NULL COMMENT '菜单权限编码列表',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  last_login_at DATETIME(3) NULL COMMENT '最后登录时间',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_staff_merchant_user (merchant_id, user_id),
  KEY idx_staff_user (user_id),
  KEY idx_staff_merchant_status (merchant_id, status),
  CONSTRAINT fk_staff_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  CONSTRAINT fk_staff_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商家员工表';

CREATE TABLE IF NOT EXISTS products (
  id BIGINT NOT NULL COMMENT '商品ID',
  product_no VARCHAR(64) NOT NULL COMMENT '商品编号',
  merchant_id BIGINT NOT NULL COMMENT '商家ID',
  store_id BIGINT NOT NULL COMMENT '店铺ID',
  category_id BIGINT NOT NULL COMMENT '类目ID',
  product_name VARCHAR(255) NOT NULL COMMENT '商品名称',
  main_image_url VARCHAR(500) NULL COMMENT '主图URL',
  detail_html MEDIUMTEXT NULL COMMENT '商品详情HTML',
  audit_status VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, APPROVED, REJECTED',
  sale_status VARCHAR(32) NOT NULL DEFAULT 'OFF_SALE' COMMENT 'ON_SALE, OFF_SALE',
  reject_reason VARCHAR(500) NULL COMMENT '驳回原因',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_products_no (product_no),
  KEY idx_products_store_status (store_id, sale_status, audit_status),
  KEY idx_products_merchant_status (merchant_id, sale_status, audit_status),
  KEY idx_products_category (category_id),
  KEY idx_products_name (product_name),
  FULLTEXT KEY ft_products_search (product_name, detail_html),
  CONSTRAINT fk_products_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  CONSTRAINT fk_products_store FOREIGN KEY (store_id) REFERENCES stores (id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商品SPU表';

CREATE TABLE IF NOT EXISTS product_skus (
  id BIGINT NOT NULL COMMENT 'SKU ID',
  sku_no VARCHAR(64) NOT NULL COMMENT 'SKU编号',
  product_id BIGINT NOT NULL COMMENT '商品ID',
  sku_name VARCHAR(255) NOT NULL COMMENT 'SKU名称',
  sale_price DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '售价',
  original_price DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '划线价',
  sku_attrs JSON NULL COMMENT '规格属性',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_skus_no (sku_no),
  KEY idx_skus_product (product_id),
  CONSTRAINT fk_skus_product FOREIGN KEY (product_id) REFERENCES products (id),
  CHECK (sale_price >= 0),
  CHECK (original_price >= 0),
  CHECK (sale_price <= original_price)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='商品SKU表';

CREATE TABLE IF NOT EXISTS sku_inventories (
  id BIGINT NOT NULL COMMENT '库存ID',
  sku_id BIGINT NOT NULL COMMENT 'SKU ID',
  total_stock INT NOT NULL DEFAULT 0 COMMENT '总库存',
  locked_stock INT NOT NULL DEFAULT 0 COMMENT '锁定库存',
  available_stock INT NOT NULL DEFAULT 0 COMMENT '可售库存',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED, DISABLED',
  remark VARCHAR(500) NULL COMMENT '备注',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL COMMENT '软删除时间',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_inventory_sku (sku_id),
  CONSTRAINT fk_inventory_sku FOREIGN KEY (sku_id) REFERENCES product_skus (id),
  CHECK (total_stock >= 0),
  CHECK (locked_stock >= 0),
  CHECK (available_stock >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='SKU库存表';

